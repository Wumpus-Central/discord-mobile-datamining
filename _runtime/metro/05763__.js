import _mod5764 from "05764__.js";

export default function toInteger(arg0) {
  const tmp = _mod5764(arg0);
  const result = tmp % 1;
  let num = 0;
  if (tmp == tmp) {
    let diff = tmp;
    if (result) {
      diff = tmp - result;
    }
    num = diff;
  }
  return num;
}
