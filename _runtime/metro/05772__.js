import _mod5773 from "05773__.js";

export default function toInteger(arg0) {
  const tmp = _mod5773(arg0);
  const result = tmp % 1;
  let num = 0;
  if (tmp == tmp) {
    let diff = tmp;
    if (result) {
      diff = tmp - result;
    }
    num = diff;
  }
  return num;
}
