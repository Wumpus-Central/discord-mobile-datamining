import _mod5707 from "05707__.js";

export default function toInteger(arg0) {
  const tmp = _mod5707(arg0);
  const result = tmp % 1;
  let num = 0;
  if (tmp == tmp) {
    let diff = tmp;
    if (result) {
      diff = tmp - result;
    }
    num = diff;
  }
  return num;
}
