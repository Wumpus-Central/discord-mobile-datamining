import _mod4595 from "04595__.js";

export default function toInteger(arg0) {
  const tmp = _mod4595(arg0);
  const result = tmp % 1;
  let num = 0;
  if (tmp == tmp) {
    let diff = tmp;
    if (result) {
      diff = tmp - result;
    }
    num = diff;
  }
  return num;
}
